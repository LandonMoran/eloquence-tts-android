    private EmojiExpander() {}

    /** Strip ZWJ (zero-width joiner), variation selectors and skin tones. */
    private static boolean isEmojiComponent(int cp) {
        return cp == 0x200D || cp == 0xFE0F || cp == 0xFE0E
                || (cp >= 0x1F3FB && cp <= 0x1F3FF);
    }

    /**
     * Replace emoji with spoken names. Unknown emoji codepoints are dropped
     * so they do not reach the engine as unmappable bytes; ZWJ sequences are
     * joined without spaces (e.g. family reads "man woman girl boy").
     */
    public static String expand(String input) {
        if (input == null || input.isEmpty()) return input;
        StringBuilder sb = new StringBuilder(input.length() + 16);
        int i = 0, adjust = 0;
        boolean lastWasName = false;
        while (i < input.length()) {
            int cp = input.codePointAt(i);
            i += Character.charCount(cp);
            if (isEmojiComponent(cp)) {
                adjust--;
                continue;
            }
            String name = NAMES.get(cp);
            if (name != null) {
                if (lastWasName) sb.append(' ');
                else if (sb.length() > 0 && !Character.isWhitespace(sb.charAt(sb.length() - 1))) sb.append(' ');
                sb.append(name);
                lastWasName = true;
            } else {
                sb.appendCodePoint(cp);
                lastWasName = false;
            }
        }
        return sb.toString();
    }
